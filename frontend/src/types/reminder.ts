export function getSearchRemindersForDate(
  dateStr: string,
  remindersList: SearchReminder[]
): SearchReminder[] {
  const matching = remindersList.filter((r) => r.date === dateStr)
  if (matching.length > 0) return matching

  const parsed = parseDate(dateStr)
  if (!parsed) return []

  const dayDisplay = formatDayDisplay(parsed)
  const firesAtDate = formatDisplayDate(parsed)
  const isPast = parsed.getTime() < new Date(2026, 8, 11).getTime()

  return [
    {
      id: `${dateStr.replace(/\//g, '-')}-1`,
      date: dateStr,
      dateDisplay: dayDisplay,
      time: '09:30',
      icon: '☕',
      title: 'Morning sync & team plan',
      channels: ['Slack', 'Push'],
      recipient: '@me',
      status: isPast ? 'DELIVERED' : 'PENDING',
      important: false,
      category: 'Culture',
      firesAt: `${dayDisplay} ${firesAtDate}, 09:30`,
      timeZone: 'Europe/London',
      createdAt: '1 Feb 2026',
      completedAt: isPast ? `${firesAtDate}, 09:30` : '—',
      recurrence: 'Daily',
    },
    {
      id: `${dateStr.replace(/\//g, '-')}-2`,
      date: dateStr,
      dateDisplay: dayDisplay,
      time: '14:00',
      icon: '🌿',
      title: 'Health & wellness check-in',
      channels: ['Push'],
      recipient: 'me@meinc.app',
      status: isPast ? 'DELIVERED' : 'PENDING',
      important: false,
      category: 'Culture',
      firesAt: `${dayDisplay} ${firesAtDate}, 14:00`,
      timeZone: 'Europe/London',
      createdAt: '5 Feb 2026',
      completedAt: isPast ? `${firesAtDate}, 14:00` : '—',
      recurrence: 'Weekly',
    },
  ]
}


