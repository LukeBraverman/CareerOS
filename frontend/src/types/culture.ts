export interface CultureReminder {
  id: string
  date: string // DD/MM/YYYY
  isoDate: string // YYYY-MM-DD
  dateDisplay: string // e.g. "Tue 6 Jan"
  time: string
  icon: string
  title: string
  category: 'Culture' | 'Travel'
  channels: string[]
  recipient: string
  recurrence: string
  status: 'DELIVERED' | 'PENDING'
  important: boolean
  monthIndex: number
  firesAt: string
  timeZone: string
  createdAt: string
  completedAt?: string
  metadata?: Record<string, string>
}

